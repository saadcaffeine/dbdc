"""
dbdc_table.py -- position tables for the DBDC refreshable braille cell.

Each DBDC cell is one cam disc with two tracks (left column = dots 1-2-3,
right column = dots 4-5-6). The rim carries the de Bruijn sequence B(4,3):
64 positions, each holding a 2-bit symbol (2*left + right). The three pins
of a column read three consecutive positions k+1 (top row), k (middle),
k-1 (bottom), so every one of the 64 six-dot patterns appears at exactly
one disc position k.

Usage:
    python3 dbdc_table.py                    # write everything to ./generated
    python3 dbdc_table.py --check-scad ../hardware/cad/dbdc_3cell.scad
    python3 dbdc_table.py --text "hello"     # print positions for a string (uncontracted letters)

Outputs (in --out, default ./generated):
    dbdc_positions.h     C header: sequence + pattern->position lookup
    dbdc_positions.json  same data for scripts / web
    position_table.md    Markdown table for the docs
    debruijn_strip.svg   unrolled two-track diagram
"""
import argparse
import json
import math
import os
import re
import sys

POSITIONS = 64
STEP_DEG = 360.0 / POSITIONS            # 5.625 degrees per position
DOT_PITCH_MM = 2.5
CAM_RADIUS_MM = DOT_PITCH_MM / math.sin(math.radians(STEP_DEG))
WHEEL_TEETH = 64                        # must match gear_teeth in the CAD: one worm turn per position


def de_bruijn(k: int, n: int) -> list[int]:
    """Lexicographically smallest de Bruijn sequence B(k, n) (FKM algorithm)."""
    a = [0] * k * n
    seq: list[int] = []

    def db(t: int, p: int) -> None:
        if t > n:
            if n % p == 0:
                seq.extend(a[1:p + 1])
        else:
            a[t] = a[t - p]
            db(t + 1, p)
            for j in range(a[t - p] + 1, k):
                a[t] = j
                db(t + 1, t)

    db(1, 1)
    return seq


SEQ = de_bruijn(4, 3)


def sym(i: int) -> int:
    return SEQ[i % POSITIONS]


def left_bit(i: int) -> int:
    return sym(i) >> 1


def right_bit(i: int) -> int:
    return sym(i) & 1


def pattern_at(k: int) -> int:
    """6-bit dot mask (bit0 = dot 1 ... bit5 = dot 6) shown at disc position k."""
    dots = [left_bit(k + 1), left_bit(k), left_bit(k - 1),     # dots 1, 2, 3
            right_bit(k + 1), right_bit(k), right_bit(k - 1)]  # dots 4, 5, 6
    return sum(b << i for i, b in enumerate(dots))


def build_tables() -> tuple[list[int], list[int]]:
    pos_to_mask = [pattern_at(k) for k in range(POSITIONS)]
    mask_to_pos = [-1] * POSITIONS
    for k, m in enumerate(pos_to_mask):
        if mask_to_pos[m] != -1:
            raise AssertionError(f"pattern {m:06b} appears twice")
        mask_to_pos[m] = k
    if -1 in mask_to_pos:
        raise AssertionError("not every pattern is reachable")
    return pos_to_mask, mask_to_pos


def mask_to_dots(m: int) -> str:
    return "".join(str(d + 1) for d in range(6) if m >> d & 1) or "-"


def mask_to_unicode(m: int) -> str:
    return chr(0x2800 + m)        # Unicode braille patterns use the same bit order


def shortest_move(a: int, b: int) -> int:
    """Signed number of positions to move from a to b the short way round."""
    d = (b - a) % POSITIONS
    return d - POSITIONS if d > POSITIONS // 2 else d


# uncontracted English letters a-z (dot lists) for the --text helper
LETTERS = {
    "a": "1", "b": "12", "c": "14", "d": "145", "e": "15", "f": "124", "g": "1245",
    "h": "125", "i": "24", "j": "245", "k": "13", "l": "123", "m": "134", "n": "1345",
    "o": "135", "p": "1234", "q": "12345", "r": "1235", "s": "234", "t": "2345",
    "u": "136", "v": "1236", "w": "2456", "x": "1346", "y": "13456", "z": "1356", " ": "",
}


def dots_to_mask(dots: str) -> int:
    return sum(1 << (int(d) - 1) for d in dots)


def write_c_header(path: str, pos_to_mask: list[int], mask_to_pos: list[int]) -> None:
    turns = WHEEL_TEETH / POSITIONS
    with open(path, "w") as f:
        f.write("// SPDX-FileCopyrightText: 2026 Saad Chinoy\n")
        f.write("// SPDX-License-Identifier: MIT\n")
        f.write("// Generated by software/dbdc_table.py -- do not edit by hand.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define DBDC_POSITIONS {POSITIONS}\n")
        f.write(f"#define DBDC_STEP_DEG {STEP_DEG}f\n")
        f.write(f"#define DBDC_WHEEL_TEETH {WHEEL_TEETH}\n")
        f.write(f"#define DBDC_WORM_TURNS_PER_POSITION {turns:g}\n")
        f.write("#define DBDC_INDEX_PULSES_PER_POSITION 1  // index magnet on the worm, hall switch on the rail\n")
        f.write("// Homing: position 0 = the middle index pulse of those seen while the home switch is active.\n\n")
        f.write("// Rim symbols, 2*left_track + right_track, position 0..63\n")
        f.write("static const uint8_t DBDC_SEQUENCE[64] = {\n")
        for r in range(0, 64, 16):
            f.write("    " + ", ".join(str(x) for x in SEQ[r:r + 16]) + ",\n")
        f.write("};\n\n")
        f.write("// Dot mask (bit0 = dot 1 ... bit5 = dot 6) -> disc position\n")
        f.write("static const uint8_t DBDC_POSITION_OF[64] = {\n")
        for r in range(0, 64, 16):
            f.write("    " + ", ".join(str(x) for x in mask_to_pos[r:r + 16]) + ",\n")
        f.write("};\n\n")
        f.write("// Disc position -> dot mask shown under the pins\n")
        f.write("static const uint8_t DBDC_PATTERN_AT[64] = {\n")
        for r in range(0, 64, 16):
            f.write("    " + ", ".join(str(x) for x in pos_to_mask[r:r + 16]) + ",\n")
        f.write("};\n")


def write_markdown(path: str, mask_to_pos: list[int]) -> None:
    letters = {dots_to_mask(v): k for k, v in LETTERS.items() if k != " "}
    with open(path, "w") as f:
        f.write("| Braille | Dots | Mask | Position | Angle | Letter |\n")
        f.write("|:---:|:---|---:|---:|---:|:---:|\n")
        for m in range(64):
            k = mask_to_pos[m]
            f.write(f"| {mask_to_unicode(m)} | {mask_to_dots(m)} | {m} | {k} | "
                    f"{k * STEP_DEG:.3f}° | {letters.get(m, '')} |\n")


def write_svg(path: str) -> None:
    cell = 14
    x0, y0 = 70, 40
    w = x0 + POSITIONS * cell + 30
    h = 150
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" '
           f'role="img" aria-labelledby="t d" font-family="sans-serif" font-size="11">',
           '<title id="t">DBDC disc rim, unrolled</title>',
           '<desc id="d">The two cam tracks of a DBDC disc unrolled into a strip of 64 '
           'positions. Raised positions are dark. A three-position window highlights '
           'how the pins read one complete six-dot braille pattern.</desc>',
           '<style>.on{fill:#1f2937}.off{fill:#e5e7eb}.lbl{fill:#374151}'
           '.win{fill:none;stroke:#d97706;stroke-width:2.5}'
           '@media (prefers-color-scheme: dark){.on{fill:#f3f4f6}.off{fill:#374151}'
           '.lbl{fill:#d1d5db}}</style>']
    for t, name in enumerate(["Left track (dots 1-2-3)", "Right track (dots 4-5-6)"]):
        y = y0 + t * (cell + 6)
        out.append(f'<text class="lbl" x="{x0 - 8}" y="{y + 10}" text-anchor="end">'
                   f'{"Left" if t == 0 else "Right"}</text>')
        for i in range(POSITIONS):
            b = left_bit(i) if t == 0 else right_bit(i)
            out.append(f'<rect class="{"on" if b else "off"}" x="{x0 + i * cell + 1}" '
                       f'y="{y}" width="{cell - 2}" height="{cell}" rx="2"/>')
    for i in range(0, POSITIONS, 8):
        out.append(f'<text class="lbl" x="{x0 + i * cell + cell / 2}" y="{y0 + 2 * cell + 26}" '
                   f'text-anchor="middle">{i}</text>')
    k = 21                                           # example window
    m = pattern_at(k)
    out.append(f'<rect class="win" x="{x0 + (k - 1) * cell - 1}" y="{y0 - 5}" '
               f'width="{3 * cell + 2}" height="{2 * cell + 16}" rx="4"/>')
    out.append(f'<text class="lbl" x="{x0 + k * cell + cell / 2}" y="{y0 + 2 * cell + 50}" '
               f'text-anchor="middle">positions {k - 1}-{k + 1}: dots {mask_to_dots(m)} '
               f'({mask_to_unicode(m)})</text>')
    out.append(f'<text class="lbl" x="{x0}" y="{h - 18}">64 positions x 5.625° = one turn. '
               f'Every 3-position window is a different 6-dot pattern.</text>')
    out.append("</svg>")
    with open(path, "w") as f:
        f.write("\n".join(out))


def check_scad(path: str) -> None:
    src = open(path).read()
    m = re.search(r"seq\s*=\s*\[([0-9,\s]+)\];", src)
    if not m:
        sys.exit(f"no 'seq = [...]' found in {path}")
    scad_seq = [int(x) for x in m.group(1).replace("\n", " ").split(",") if x.strip()]
    if scad_seq != SEQ:
        sys.exit("MISMATCH: the CAD sequence differs from dbdc_table.py")
    print(f"OK: {path} uses the same B(4,3) sequence ({len(SEQ)} positions)")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "generated"))
    ap.add_argument("--check-scad", metavar="FILE")
    ap.add_argument("--text", metavar="STRING", help="print disc positions for a-z text")
    args = ap.parse_args()

    pos_to_mask, mask_to_pos = build_tables()

    if args.check_scad:
        check_scad(args.check_scad)
        return
    if args.text is not None:
        prev = 0
        for ch in args.text.lower():
            if ch not in LETTERS:
                print(f"{ch!r}: not in the a-z table, skipped")
                continue
            m = dots_to_mask(LETTERS[ch])
            k = mask_to_pos[m]
            print(f"{ch!r} {mask_to_unicode(m)} dots {mask_to_dots(m):6s} -> position {k:2d}"
                  f"  (move {shortest_move(prev, k):+d} from {prev})")
            prev = k
        return

    os.makedirs(args.out, exist_ok=True)
    write_c_header(os.path.join(args.out, "dbdc_positions.h"), pos_to_mask, mask_to_pos)
    with open(os.path.join(args.out, "dbdc_positions.json"), "w") as f:
        json.dump({"positions": POSITIONS, "step_deg": STEP_DEG,
                   "cam_radius_mm": round(CAM_RADIUS_MM, 4), "sequence": SEQ,
                   "position_of_mask": mask_to_pos, "mask_at_position": pos_to_mask},
                  f, indent=1)
    write_markdown(os.path.join(args.out, "position_table.md"), mask_to_pos)
    write_svg(os.path.join(args.out, "debruijn_strip.svg"))
    print(f"wrote 4 files to {args.out}  (cam radius {CAM_RADIUS_MM:.3f} mm, "
          f"max move {POSITIONS // 2} positions)")


if __name__ == "__main__":
    main()
